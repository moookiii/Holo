"""Preserve exact M24EN English fronts; never substitute their expansion prints."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import hashlib, io, json, time
import requests
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = ROOT/'research/dragon-discovery'
PUBLIC = ROOT/'public/cards/pokemon/dragon-discovery'
HOLOS = {2, 3, 8, 10, 11, 12, 15}
LAUNCH = 'https://corporate.mcdonalds.com/corpmcd/our-stories/article/pokemon-themed-happy-meal.html'

def fetch(url):
    for attempt in range(4):
        try:
            r = requests.get(url, timeout=60); r.raise_for_status(); return r.content
        except requests.RequestException:
            if attempt==3: raise
            time.sleep(attempt+1)

def digest(data): return hashlib.sha256(data).hexdigest()

def main():
    ARCHIVE.mkdir(parents=True, exist_ok=True); PUBLIC.mkdir(parents=True, exist_ok=True)
    meta = json.loads(fetch('https://api.tcgdex.net/v2/en/sets/2024sv'))
    (ARCHIVE/'set.json').write_text(json.dumps(meta, indent=2)+'\n')
    def acquire(summary):
        card = json.loads(fetch('https://api.tcgdex.net/v2/en/cards/'+summary['id']))
        number = int(card['localId']); variant = 'holo' if number in HOLOS else 'normal'
        products = {v['thirdParty']['tcgplayer'] for v in card['variants_detailed'] if v['type']==variant}
        if len(products)!=1: raise ValueError('Ambiguous exact image '+card['id'])
        product = products.pop(); url = f'https://tcgplayer-cdn.tcgplayer.com/product/{product}_in_1000x1000.jpg'
        raw = fetch(url); (ARCHIVE/(card['id']+'.jpg')).write_bytes(raw)
        im = Image.open(io.BytesIO(raw)); im.save(PUBLIC/(card['localId']+'.png'))
        record = {k:card[k] for k in ('id','localId','name','category','types','stage') if k in card}
        if 'evolveFrom' in card: record['evolveFrom']=card['evolveFrom']
        record.update(rarity='Promo', variants=[variant], foil={'holo':'CONFETTI'} if variant=='holo' else {})
        evidence = {'cardId':card['id'], 'name':card['name'], 'collectorNumber':f'{number:03d}/015',
            'variant':variant, 'printedSetCode':'M24EN', 'metadataUrl':'https://api.tcgdex.net/v2/en/cards/'+card['id'],
            'imageUrl':url, 'tcgplayerProductId':product, 'sourceDimensions':list(im.size), 'sourceSha256':digest(raw),
            'frontSha256':digest((PUBLIC/(card['localId']+'.png')).read_bytes()),
            'transformations':'JPEG decode to PNG only; no crop, rotation, rescale or retouch.',
            'finishStatus':'Photographed confetti retained; animated foil deferred pending a clean exact-print front and protection.' if variant=='holo' else 'Nonfoil print.',
            'tcglStatus':'No McDonald set entry in the English TCGL export index; no etch fabricated.'}
        (PUBLIC/(card['localId']+'-source.json')).write_text(json.dumps(evidence,indent=2)+'\n')
        return record
    with ThreadPoolExecutor(max_workers=8) as pool: records=list(pool.map(acquire,meta['cards']))
    text='// Exact M24EN printings; generated by scripts/prepare-dragon-discovery.py.\nimport type { PokemonCard } from "../types.ts";\n'
    text+='export const dragonDiscoveryRecords: readonly Omit<PokemonCard, "setId" | "setName" | "seriesId" | "seriesName" | "era">[] = '+json.dumps(records,indent=2)+';\n'
    (ROOT/'src/pokemon/data/dragon-discovery.generated.ts').write_text(text)
    # Traced wrapper outline in the original photograph; remove the surrounding toys.
    url='https://www.pokebeach.com/news/2025/01/McDonalds-Dragon-Discovery-Booster-Pack.jpg'
    raw=fetch(url); (ARCHIVE/'pack.jpg').write_bytes(raw)
    im=Image.open(io.BytesIO(raw)).convert('RGBA'); scale=4
    mask=Image.new('L',(im.width*scale,im.height*scale))
    outline=[(501,156),(994,160),(999,261),(1003,423),(1005,625),(1008,822),(1011,1053),(1007,1089),(534,1098),(513,1092),(511,1080),(509,958),(507,763),(504,556),(500,359),(498,178)]
    ImageDraw.Draw(mask).polygon([(x*scale,y*scale) for x,y in outline],fill=255)
    mask=mask.resize(im.size,Image.Resampling.LANCZOS); im.putalpha(mask)
    box=mask.getbbox(); im=im.crop(box)
    pack=ROOT/'public/packs/pokemon/2024sv-front.png'; im.save(pack)
    (PUBLIC/'pack-source.json').write_text(json.dumps({'url':url,'sourceDimensions':[1042,1133],
        'sourceSha256':digest(raw),'cropBox':list(box),'outline':outline,'dimensions':list(im.size),
        'sha256':digest(pack.read_bytes()),'method':'Manually traced antialiased alpha silhouette; tight crop, no artwork stretch.',
        'releaseDate':'2025-01-21','releaseSource':LAUNCH},indent=2)+'\n')

if __name__=='__main__': main()
