import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

// Phase 1 only: ordinary, unstamped Wizards Black Star Promo prints.
const numbers = [1, 6, 7, 8, 12, 14, 16, ...range(19, 23), ...range(25, 32), ...range(36, 49)];
const root = new URL('../public/cards/pokemon/wizards-promos/', import.meta.url);
const data = new URL('../src/pokemon/data/wizards-promos.generated.ts', import.meta.url);
function range(start, end) { return Array.from({ length: end - start + 1 }, (_, i) => start + i); }
async function get(url) {
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
      if (!response.ok) throw new Error(`${response.status} ${url}`);
      return response;
    } catch (error) {
      if (attempt === 3) throw error;
      await new Promise(resolve => setTimeout(resolve, 500 * 2 ** attempt));
    }
  }
}
await mkdir(root, { recursive: true });
// TCGdex's #1 scan depicts a stamped special print. Use a photographed
// ordinary card and retain its rectification instructions separately.
execFileSync('python', ['scripts/prepare-wizards-promo-1.py'], { cwd: new URL('..', import.meta.url) });
const records = [], sources = [];
// Bounded concurrency keeps the source service responsive.
for (let offset = 0; offset < numbers.length; offset += 3) {
  const batch = await Promise.all(numbers.slice(offset, offset + 3).map(async number => {
    const id = `basep-${number}`;
    const metadataUrl = `https://api.tcgdex.net/v2/en/cards/${id}`;
    const metadata = await (await get(metadataUrl)).json();
    const ordinary = metadata.variants_detailed?.some(v => v.type === 'normal' && v.size === 'standard' && !v.stamp?.length && !v.subtype);
    if (metadata.id !== id || metadata.localId !== String(number) || metadata.set?.id !== 'basep'
      || !ordinary || metadata.variants?.holo || metadata.variants?.reverse) {
      throw new Error(`Not an ordinary unstamped non-holo promo: ${id}`);
    }
    const imageUrl = number === 1
      ? 'https://www.wildcardcyclone.com/cdn/shop/products/Pikachu1BasicPokemonBlackStarPromo_800x.jpg?v=1606705896'
      : `https://assets.tcgdex.net/en/base/basep/${number}/high.png`;
    const bytes = number === 1 ? await readFile(new URL('1.png', root))
      : Buffer.from(await (await get(imageUrl)).arrayBuffer());
    if (bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error(`Not a PNG: ${imageUrl}`);
    return {
      number, bytes,
      record: { id, localId: String(number), name: metadata.name, rarity: metadata.rarity,
        category: metadata.category, stage: metadata.stage, evolveFrom: metadata.evolveFrom,
        types: metadata.types, trainerType: metadata.trainerType, front: `${number}.png` },
      source: { id, metadata: metadataUrl, image: imageUrl, sha256: createHash('sha256').update(bytes).digest('hex') },
    };
  }));
  for (const item of batch) {
    await writeFile(new URL(`${item.number}.png`, root), item.bytes);
    records.push(item.record); sources.push(item.source);
  }
  console.log(`Fetched ${Math.min(offset + 3, numbers.length)}/${numbers.length}`);
}
await writeFile(data, `// Generated by scripts/fetch-wizards-promos.mjs from TCGdex.\nexport const wizardsPromoRecords = ${JSON.stringify(records, null, 2)} as const;\n`);
await writeFile(new URL('sources.json', root), `${JSON.stringify(sources, null, 2)}\n`);
